"""Acquire CC0 PBR materials from ambientCG; preserve 4K source maps and derive mobile maps.
Generated by CodeRabbit. Run in a Python environment with Pillow. Sources and hashes
are recorded in surfaces.json. Archive cache is outside the checkout.
"""
import concurrent.futures,hashlib,json,pathlib,sys,urllib.request,zipfile,time
from PIL import Image
ROOT=pathlib.Path(__file__).resolve().parents[1]
IDS='Ground037 Ground048 Ground054 Ground068 Ground080 Ground085 Ground086 Ground097 Ground103 Grass001 Grass004 Grass005 Rock020 Rock030 Rock035 Rock051 Rock058 Rock060 Bricks059 Bricks066 Bricks084 Bricks094 PavingStones070 PavingStones128 WoodFloor051 WoodFloor043 Marble006 Marble012 Moss002 Gravel023 Gravel041 Ground104 Rock061 Ground105 Grass006 Grass007 Ground109 Ground110 PavingStones138 PavingStones142 WoodFloor064 Marble016'.split()
CACHE=pathlib.Path(sys.argv[1]);CACHE.mkdir(parents=True,exist_ok=True)
def get(url):
    for attempt in range(4):
        try:return urllib.request.urlopen(urllib.request.Request(url,headers={"User-Agent":"Mozilla/5.0","Referer":"https://ambientcg.com/"}),timeout=120)
        except Exception:
            if attempt==3:raise
            time.sleep(2**attempt)
def one(id):
    archive=CACHE/(id+'_4K-JPG.zip')
    url='https://ambientcg.com/get?file='+archive.name
    if not archive.exists():
        import shutil
        with get(url) as src,archive.with_suffix('.part').open('wb') as out:shutil.copyfileobj(src,out)
        archive.with_suffix('.part').replace(archive)
    dest=ROOT/'game/assets/enrichment/surfaces'/id;dest.mkdir(parents=True,exist_ok=True)
    files=[]
    with zipfile.ZipFile(archive) as z:
        names=z.namelist()
        for role,suffix in [('albedo','Color'),('normal','NormalGL'),('roughness','Roughness'),('ao','AmbientOcclusion')]:
            match=next((n for n in names if n.endswith('_'+suffix+'.jpg')),None)
            if match is None:continue
            image=Image.open(z.open(match)).convert('RGB')
            for quality,size in [('high',4096),('mobile',1024)]:
                p=dest/(quality+'_'+role+'.jpg')
                if p.exists():pass
                elif quality=='high':p.write_bytes(z.read(match))
                else:image.resize((size,size),Image.Resampling.LANCZOS).save(p,quality=90)
                files.append({'path':'res://'+str(p.relative_to(ROOT/'game')),'role':role,'quality':quality,'sha256':hashlib.file_digest(p.open('rb'),'sha256').hexdigest(),'bytes':p.stat().st_size})
                # VRAM compressed, mipmapped textures. Explicit imports prevent detection-dependent settings.
                if not (p.parent/(p.name+'.import')).exists():(p.parent/(p.name+'.import')).write_text('[remap]\nimporter="texture"\ntype="CompressedTexture2D"\n[params]\ncompress/mode=2\ncompress/high_quality=false\nmipmaps/generate=true\nprocess/normal_map_invert_y=false\n')
    result={'id':id,'source':url,'page':'https://ambientcg.com/a/'+id,'license':'CC0-1.0','license_url':'https://docs.ambientcg.com/license/','archive_sha256':hashlib.file_digest(archive.open('rb'),'sha256').hexdigest(),'maps':files}
    print(id,'ready',sum(x['bytes'] for x in files),flush=True);return result
if __name__=='__main__':
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:assets=list(pool.map(one,IDS))
    (ROOT/'game/data/surfaces.json').write_text(json.dumps({'generated_by':'CodeRabbit','materials':assets},indent=2)+'\n')
