"""Build source-only regional packs and an exact artifact inventory; no padding files.
Generated by CodeRabbit. Call after the Android export completes.
"""
import hashlib,json,pathlib,zipfile,sys,collections
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=pathlib.Path(sys.argv[1]);OUT.mkdir(parents=True,exist_ok=True)
def sha(p):
 with p.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()
regions=json.loads((ROOT/'game/data/regions.json').read_text())['regions'];artifacts=[]
for land,name in enumerate(['death','beauty','prosperity']):
 ids=sorted({r['surface'] for r in regions if r['land']==land})
 path=OUT/f'3lands-0.3.0-source-surfaces-{name}.zip'
 with zipfile.ZipFile(path,'w',compression=zipfile.ZIP_STORED,allowZip64=True) as z:
  for id in ids:
   for f in sorted((ROOT/'game/assets/enrichment/surfaces'/id).iterdir()):
    if f.is_file():z.write(f,str(f.relative_to(ROOT)))
 artifacts.append({'name':path.name,'bytes':path.stat().st_size,'sha256':sha(path),'purpose':'Source materials; not required to play the APK'})
apk=ROOT/'builds/3lands-0.3.0-arm64.apk'
with zipfile.ZipFile(apk) as z:
 sizes={'apk_file_bytes':apk.stat().st_size,'apk_entries_compressed_bytes':sum(f.compress_size for f in z.infolist()),'apk_entries_uncompressed_bytes':sum(f.file_size for f in z.infolist()),'packaged_assets_uncompressed_bytes':sum(f.file_size for f in z.infolist() if f.filename.startswith('assets/'))}
artifacts.insert(0,{'name':apk.name,'bytes':apk.stat().st_size,'sha256':sha(apk),'purpose':'Standalone offline Android ARM64 development build'})
models=json.loads((ROOT/'game/data/library.json').read_text())['models']
inventory={'generated_by':'CodeRabbit','version':'0.3.0','engine':'4.7.2','counts':dict(collections.Counter(m['category'] for m in models)),'models_total':len(models),'imported_animation_clips':sum(len(m['animations']) for m in models),'regions':len(regions),'materials':len(json.loads((ROOT/'game/data/surfaces.json').read_text())['materials']),'audio_files':len(list((ROOT/'game/assets/enrichment/audio').glob('*.ogg'))),'sizes':sizes,'artifacts':artifacts}
(OUT/'3lands-0.3.0-inventory.json').write_text(json.dumps(inventory,indent=2)+'\n')
(OUT/'SHA256SUMS.txt').write_text(''.join(a['sha256']+'  '+a['name']+'\n' for a in artifacts))
print(json.dumps(inventory,indent=2))
