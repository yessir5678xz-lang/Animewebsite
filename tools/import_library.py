"""Import verified Kenney CC0 archives. Downloads use the public site's official flow.
Generated by CodeRabbit for Three Lands. No credentials required.
Usage: python tools/import_library.py /path/to/archives
"""
import hashlib,json,pathlib,sys,zipfile,struct
ROOT=pathlib.Path(__file__).resolve().parents[1]
PACKS=['nature-kit','fantasy-town-kit','castle-kit','graveyard-kit','mini-dungeon','blocky-characters','survival-kit']
def category(kit,name):
    if name.startswith('character'):return 'characters'
    if any(x in name.lower() for x in ['tree','plant','flower','grass','bush','cactus','crop','mushroom','lily','log','stump']):return 'vegetation'
    if any(x in name.lower() for x in ['wall','roof','tower','bridge','house','crypt','gate','stairs','floor','window','door','column','pillar','balcony','fence','arch','cliff']):return 'architecture'
    return 'props'
def main():
    entries=[];sources=[]
    for kit in PACKS:
        archive=pathlib.Path(sys.argv[1])/(kit+'.zip')
        with zipfile.ZipFile(archive) as z:
            license_text=z.read(next(n for n in z.namelist() if n.lower().endswith('license.txt')))
            assert b'CC0' in license_text
            dest=ROOT/'game/assets/enrichment/models'/kit;dest.mkdir(parents=True,exist_ok=True)
            (dest/'LICENSE.txt').write_bytes(license_text)
            prefix=next(n.rsplit('/',1)[0]+'/' for n in z.namelist() if n.endswith('.glb'))
            for name in z.namelist():
                if not name.startswith(prefix) or not name.endswith(('.glb','.png','.bin')):continue
                relative=pathlib.PurePosixPath(name[len(prefix):]);assert '..' not in relative.parts
                p=dest/relative;p.parent.mkdir(parents=True,exist_ok=True);b=z.read(name);p.write_bytes(b)
                if p.suffix!='.glb':continue
                length=struct.unpack_from('<I',b,12)[0];gltf=json.loads(b[20:20+length])
                entries.append({'id':kit+'/'+p.stem,'path':'res://'+str(p.relative_to(ROOT/'game')),'kit':kit,'category':category(kit,p.stem),'sha256':hashlib.sha256(b).hexdigest(),'bytes':len(b),'animations':[a.get('name','') for a in gltf.get('animations',[])]})
            sources.append({'name':kit,'url':'https://kenney.nl/assets/'+kit,'license':'CC0-1.0','license_url':'https://creativecommons.org/publicdomain/zero/1.0/','archive_sha256':hashlib.file_digest(archive.open('rb'),'sha256').hexdigest(),'license_path':str((dest/'LICENSE.txt').relative_to(ROOT))})
    (ROOT/'game/data/library.json').write_text(json.dumps({'generated_by':'CodeRabbit','models':entries,'sources':sources},indent=2)+'\n')
    from collections import Counter
    print(len(entries),dict(Counter(e['category'] for e in entries)))
if __name__=='__main__':main()
